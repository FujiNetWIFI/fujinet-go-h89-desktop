#!/usr/bin/env python3
"""Generate roms_embedded.c: the recognised H89/H19 ROMs in a directory,
or nothing at all.

The H89's monitor ROMs, the H-17 controller ROM and the H19's character
generator are copyrighted Heath/Zenith (and third-party) firmware and are
not redistributed by this project (COMPLIANCE.md). --none is therefore the
SHIPPING configuration, not an error path: it emits an empty table, and the
app asks the user to import the ROMs on first start.

With a directory (WITH_H89_ROMS=ON, a developer build), every file in it --
and every member of every .zip in it, so MAME's own h89.zip and
heath_tlb.zip can be dropped in as they are -- whose size and CRC-32 match
the table (core/src/roms.c) is embedded under MAME's file name, whatever it
is called locally. Anything else is ignored.

usage: embed-roms.py <out.c> <dir>
       embed-roms.py --none <out.c>
"""

import sys
import zipfile
import zlib
from pathlib import Path

# (size, crc) -> MAME's file name; mirrors s_roms[] in core/src/roms.c
KNOWN = {
    (0x0800, 0x26E80AE3): "2716_444-19_h17.u520",
    (0x0800, 0xD595AC1D): "2716_444-29_h19font.u420",
    (0x1000, 0xC4FF47C5): "2732_444-142_mtr90.u518",
    (0x1000, 0xF10FCA03): "2732_444-84_mtr90.u518",
    (0x0800, 0x8F507972): "2716_444-62_mtr89.u518",
    (0x0800, 0x093AFB79): "2716_444-40_mtr88.u518",
    (0x1000, 0x7E75D6F4): "2732_444_84b_mms.u518",
    (0x1000, 0x0E541A7E): "2732_444_84a_mms.u518",
    (0x1000, 0xFD491592): "2732_kmr100_v3_a_02.u518",
    (0x1000, 0xE26B29A9): "2732_mtrhex_4k.u518",
    (0x0800, 0x842A306A): "2716_mtrhex.u518",
    (0x1000, 0xED8BDBE9): "2732_ets_4k.u518",
    (0x1000, 0xC5C6B799): "2732_sigma_rom_v_1.3.bin",
}

HEADER = """/* Generated by tools/roms/embed-roms.py -- do not edit.
 * SPDX-License-Identifier: GPL-3.0-or-later
 */
#include "roms_embedded.h"

"""


def candidates(src):
    """Every (bytes) blob in the directory: loose files and zip members."""
    for f in sorted(src.iterdir()) if src.is_dir() else []:
        if not f.is_file():
            continue
        if f.suffix.lower() == ".zip":
            try:
                with zipfile.ZipFile(f) as z:
                    for info in z.infolist():
                        if (info.file_size, info.CRC) in KNOWN:
                            yield z.read(info)
            except zipfile.BadZipFile:
                pass
        elif f.stat().st_size <= 0x1000:
            yield f.read_bytes()


def main():
    args = sys.argv[1:]
    if args and args[0] == "--none":
        if len(args) != 2:
            sys.exit(__doc__)
        Path(args[1]).write_text(
            HEADER
            + "/* Nothing embedded -- the shipping configuration. */\n"
            + "const h89_embedded_rom h89_embedded_roms[1] = { { 0, 0, 0 } };\n"
            + "const unsigned h89_embedded_rom_count = 0;\n")
        return 0

    if len(args) != 2:
        sys.exit(__doc__)
    out, src = Path(args[0]), Path(args[1])
    found = {}
    for data in candidates(src):
        name = KNOWN.get((len(data), zlib.crc32(data) & 0xFFFFFFFF))
        if name and name not in found:
            found[name] = data

    body = [HEADER,
            "/* WITH_H89_ROMS=ON: a developer build. NOT redistributable.\n"
            " * See COMPLIANCE.md. */\n"]
    for i, (name, data) in enumerate(found.items()):
        body.append("static const uint8_t rom%d[%d] = {\n" % (i, len(data)))
        for j in range(0, len(data), 16):
            body.append("    " + ",".join("0x%02X" % b for b in data[j:j + 16]) + ",\n")
        body.append("};\n")
    body.append("\nconst h89_embedded_rom h89_embedded_roms[%d] = {\n" % max(1, len(found)))
    for i, (name, data) in enumerate(found.items()):
        body.append('    { "%s", rom%d, %d },\n' % (name, i, len(data)))
    if not found:
        body.append("    { 0, 0, 0 },\n")
    body.append("};\nconst unsigned h89_embedded_rom_count = %d;\n" % len(found))
    out.write_text("".join(body))
    print("embed-roms: %d image(s): %s" % (len(found), ", ".join(found) or "none"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
